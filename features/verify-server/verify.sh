#!/usr/bin/env bash
# verify.sh — drive a real server route against an isolated Compose stack and
# keep the evidence. Steps map 1:1 to the verify-server skill:
#
#   verify.sh launch              start webapp + postgres + qdrant (own project)
#   verify.sh doctor              check the stack is the one we meant to start
#   verify.sh drive <feature>     health | calendar-today | sessions-dates | admin-static-entities
#   verify.sh evidence            snapshot ps, logs, summary into features/evidence/<run>/
#   verify.sh cleanup             tear down ONLY this run's project; evidence stays
#
# Isolation: every docker call goes through `-p <project>` with a unique
# project name, a generated env file (no server/.env, no real secrets), a
# loopback-only port and a project-scoped data volume. Nothing here prunes,
# touches other projects, or reads server/.env.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
HERE="$ROOT/features/verify-server"
SCRATCH="$ROOT/.verify"
CURRENT="$SCRATCH/current"

die() { echo "verify: $*" >&2; exit 1; }

load_state() {
  [ -f "$CURRENT" ] || die "no active run (run 'launch' first)"
  RUN_ID="$(cat "$CURRENT")"
  RUN_DIR="$SCRATCH/$RUN_ID"
  [ -f "$RUN_DIR/state.env" ] || die "run $RUN_ID has no state (already cleaned up?)"
  # shellcheck disable=SC1091
  . "$RUN_DIR/state.env"
  EVID="$ROOT/features/evidence/$RUN_ID"
  mkdir -p "$EVID"
}

dc() {
  docker compose -p "$PROJECT" --project-directory "$ROOT/server" \
    --env-file "$RUN_DIR/env" \
    -f "$ROOT/server/docker-compose.yml" -f "$HERE/compose.verify.yml" "$@"
}

# Strip this run's generated secrets from anything headed for evidence.
redact() {
  local token password
  token="$(sed -n 's/^IOS_BEARER_TOKEN=//p' "$RUN_DIR/env")"
  password="$(sed -n 's/^POSTGRES_PASSWORD=//p' "$RUN_DIR/env")"
  sed -e "s|$token|<redacted-bearer>|g" -e "s|$password|<redacted-pg-password>|g"
}

# call <name> <METHOD> <path> <auth 1|0> [json-body]
# Records request/response/status under $EVID/<name>.* ; never records the
# Authorization header (curl reads it from a 0600 file, not argv).
call() {
  local name=$1 method=$2 path=$3 auth=$4 body=${5:-}
  local base="$EVID/$name"
  local args=(-sS -X "$method" -D "$base.response.headers" -o "$base.response.body"
              -w '%{http_code}' --max-time 30 "http://127.0.0.1:$PORT$path")
  {
    echo "$method $path"
    [ "$auth" = 1 ] && echo "Authorization: Bearer <redacted>"
    if [ -n "$body" ]; then echo "Content-Type: application/json"; echo; echo "$body"; fi
  } >"$base.request.txt"
  [ "$auth" = 1 ] && args+=(-H "@$RUN_DIR/auth.header")
  [ -n "$body" ] && args+=(-H 'Content-Type: application/json' --data "$body")
  CODE="$(curl "${args[@]}")"
  echo "$CODE" >"$base.status"
  if jq . "$base.response.body" >"$base.response.pretty.json" 2>/dev/null; then
    mv "$base.response.pretty.json" "$base.response.body"
  else
    rm -f "$base.response.pretty.json"
  fi
  echo "  $name: $method $path -> $CODE"
}

expect() { # expect <name> <want-status>
  [ "$(cat "$EVID/$1.status")" = "$2" ] || die "$1: expected HTTP $2, got $(cat "$EVID/$1.status") ($(head -c 300 "$EVID/$1.response.body"))"
}

body() { cat "$EVID/$1.response.body"; }

# --- launch ----------------------------------------------------------------

cmd_launch() {
  command -v docker >/dev/null || die "docker not found"
  command -v jq >/dev/null && command -v curl >/dev/null && command -v openssl >/dev/null \
    || die "jq, curl and openssl are required"
  docker compose version >/dev/null || die "docker compose v2 not available"
  [ ! -f "$CURRENT" ] || [ ! -f "$SCRATCH/$(cat "$CURRENT")/state.env" ] \
    || die "run $(cat "$CURRENT") is still active — run 'cleanup' first"

  local suffix stamp
  suffix="$(openssl rand -hex 4)"
  stamp="$(date -u +%Y%m%dT%H%M%SZ)"
  RUN_ID="$stamp-$suffix"
  PROJECT="vd-verify-$suffix"
  RUN_DIR="$SCRATCH/$RUN_ID"
  PORT="$(python3 -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1",0)); print(s.getsockname()[1])')"
  mkdir -p "$RUN_DIR" "$ROOT/features/evidence/$RUN_ID"
  chmod 700 "$RUN_DIR"
  EVID="$ROOT/features/evidence/$RUN_ID"

  local token password
  token="$(openssl rand -hex 32)"
  password="$(openssl rand -hex 32)"
  (
    umask 077
    cat >"$RUN_DIR/env" <<EOF
# Generated by verify.sh launch for $RUN_ID. Ephemeral; deleted by cleanup.
# TAILNET_IP is a dummy CGNAT value that satisfies bind_guard; the port is
# published on 127.0.0.1 only (compose.verify.yml).
TAILNET_IP=100.64.0.1
POSTGRES_USER=diary
POSTGRES_PASSWORD=$password
POSTGRES_DB=diary_processor
IOS_BEARER_TOKEN=$token
MSGRAPH_FIXTURE_MODE=true
OLLAMA_BASE_URL=
LIGHTRAG_URL=
LLM_VALIDATION_ENABLED=false
VECTOR_SEARCH_ENABLED=true
QDRANT_URL=http://qdrant:6333
TZ=Europe/Berlin
VERIFY_PORT=$PORT
VERIFY_ENV_FILE=$RUN_DIR/env
EOF
    printf 'Authorization: Bearer %s\n' "$token" >"$RUN_DIR/auth.header"
  )
  cat >"$RUN_DIR/state.env" <<EOF
PROJECT=$PROJECT
PORT=$PORT
EOF
  echo "$RUN_ID" >"$CURRENT"
  echo "run:     $RUN_ID"
  echo "project: $PROJECT   port: 127.0.0.1:$PORT"

  echo "==> starting postgres + qdrant"
  dc up -d --wait postgres qdrant
  echo "==> building + starting webapp (first build downloads the embedding model)"
  dc up -d --build --no-deps webapp

  echo "==> waiting for /health"
  local i
  for i in $(seq 1 90); do
    if curl -sf --max-time 3 -o /dev/null "http://127.0.0.1:$PORT/health"; then
      echo "webapp answering after ~$((i * 2))s"
      return 0
    fi
    sleep 2
  done
  dc logs --tail 60 webapp >&2 || true
  die "webapp did not answer /health within 180s (stack left up for inspection; run 'cleanup')"
}

# --- doctor ----------------------------------------------------------------

cmd_doctor() {
  load_state
  local fail=0 out="$EVID/doctor.txt"
  : >"$out"
  check() { # check <label> <command...>
    local label=$1; shift
    if "$@" >/dev/null 2>&1; then echo "PASS  $label" | tee -a "$out"
    else echo "FAIL  $label" | tee -a "$out"; fail=1; fi
  }

  local ps_json
  ps_json="$(dc ps --format json | jq -s .)"
  check "project $PROJECT has webapp, postgres, qdrant running" \
    jq -e '[.[] | select(.State=="running") | .Service] | (index("webapp") != null and index("postgres") != null and index("qdrant") != null)' <<<"$ps_json"
  check "project runs nothing else (no voxtral/whisper/GPU services)" \
    jq -e 'all(.[]; .Service == "webapp" or .Service == "postgres" or .Service == "qdrant")' <<<"$ps_json"
  check "webapp published on 127.0.0.1:$PORT only" \
    test "$(dc port webapp 8000)" = "127.0.0.1:$PORT"
  check "no container of this project publishes postgres/qdrant ports" \
    test -z "$(docker ps --filter "label=com.docker.compose.project=$PROJECT" --format '{{.Ports}}' | grep -E '5432|6333' | grep -- '->' || true)"
  check "server/.env was not used (env comes from $RUN_DIR/env)" \
    test "$(docker inspect "$(dc ps -q webapp)" --format '{{index .Config.Labels "com.docker.compose.project.environment_file"}}')" != "$ROOT/server/.env"

  call doctor-health GET /health 0
  check "GET /health -> 200 without bearer" test "$(cat "$EVID/doctor-health.status")" = 200
  check "health: postgres ok" jq -e '.upstream.postgres == "ok"' "$EVID/doctor-health.response.body"
  check "health: qdrant ok" jq -e '.upstream.qdrant == "ok"' "$EVID/doctor-health.response.body"
  check "health: msgraph is fixture (no Entra needed)" jq -e '.upstream.msgraph == "fixture"' "$EVID/doctor-health.response.body"

  call doctor-noauth GET /api/sessions/dates 0
  check "route without bearer -> 401 missing_bearer_token" \
    jq -e '.detail == "missing_bearer_token"' "$EVID/doctor-noauth.response.body"
  call doctor-auth GET /api/sessions/dates 1
  check "route with generated bearer -> 200" test "$(cat "$EVID/doctor-auth.status")" = 200

  echo "note: health.status is expected to be 'down'/'degraded' here — whisper, voxtral," >>"$out"
  echo "      ollama and lightrag are deliberately not part of this stack." >>"$out"
  [ "$fail" = 0 ] || die "doctor failed — see $out"
  echo "doctor: all checks passed"
}

# --- drive -----------------------------------------------------------------

drive_health() {
  call health GET /health 0; expect health 200
  jq -e '.upstream | has("postgres") and has("qdrant")' "$EVID/health.response.body" >/dev/null
}

drive_calendar_today() {
  local d; d="$(date +%F)"
  call calendar-today-noauth GET "/today/calendar?date=$d" 0; expect calendar-today-noauth 401
  call calendar-today GET "/today/calendar?date=$d" 1; expect calendar-today 200
  jq -e --arg d "$d" '.date == $d and (.events | type == "array") and (.events | length > 0)' \
    "$EVID/calendar-today.response.body" >/dev/null || die "calendar-today: expected fixture events for $d"
}

drive_sessions_dates() {
  call sessions-dates-noauth GET /api/sessions/dates 0; expect sessions-dates-noauth 401
  call sessions-dates GET /api/sessions/dates 1; expect sessions-dates 200
  jq -e '.dates | type == "array"' "$EVID/sessions-dates.response.body" >/dev/null
  call sessions-dates-bad GET '/api/sessions/dates?date_from=not-a-date' 1; expect sessions-dates-bad 400
  jq -e '.detail == "invalid_date_from"' "$EVID/sessions-dates-bad.response.body" >/dev/null
}

drive_admin_static_entities() {
  local name="verify-$RUN_ID" payload id
  payload="$(jq -nc --arg n "$name" '{name:$n, entity_type:"Category", description:"KA-8 verify-server probe"}')"

  call static-entity-noauth POST /api/admin/static-entities 0 "$payload"; expect static-entity-noauth 401
  call static-entity-create POST /api/admin/static-entities 1 "$payload"; expect static-entity-create 200
  id="$(jq -er '.id' "$EVID/static-entity-create.response.body")"

  # Side effect 1: visible through the API.
  call static-entity-list GET /api/admin/static-entities 1; expect static-entity-list 200
  jq -e --arg n "$name" 'any(.[]; .name == $n)' "$EVID/static-entity-list.response.body" >/dev/null \
    || die "static-entity: created row not returned by GET"

  # Side effect 2: the row really is in Postgres (not just echoed back).
  dc exec -T postgres sh -c \
    "psql -U \"\$POSTGRES_USER\" -d \"\$POSTGRES_DB\" -Atc \"SELECT id, name, entity_type, status FROM static_entities WHERE id = $id\"" \
    >"$EVID/static-entity-db-row.txt"
  grep -q "^$id|$name|Category|active$" "$EVID/static-entity-db-row.txt" \
    || die "static-entity: DB row missing/unexpected: $(cat "$EVID/static-entity-db-row.txt")"
  echo "  static-entity-db-row: $(cat "$EVID/static-entity-db-row.txt")"

  # Side effect 3: the request was logged by the real middleware, 200, no token.
  sleep 1
  dc logs --no-color --no-log-prefix webapp 2>&1 | redact \
    | grep '"path": *"/api/admin/static-entities"' >"$EVID/static-entity-request-log.jsonl" || true
  grep -q '"status_code": *200' "$EVID/static-entity-request-log.jsonl" \
    || die "static-entity: no 200 request log line for POST /api/admin/static-entities"

  # Leave the stack's DB as we found it, then prove it.
  call static-entity-delete DELETE "/api/admin/static-entities/$id" 1; expect static-entity-delete 200
  dc exec -T postgres sh -c \
    "psql -U \"\$POSTGRES_USER\" -d \"\$POSTGRES_DB\" -Atc \"SELECT count(*) FROM static_entities WHERE id = $id\"" \
    >"$EVID/static-entity-db-after-delete.txt"
  [ "$(tr -d '[:space:]' <"$EVID/static-entity-db-after-delete.txt")" = 0 ] || die "static-entity: row still present after DELETE"
}

cmd_drive() {
  load_state
  case "${1:-}" in
    health) drive_health ;;
    calendar-today) drive_calendar_today ;;
    sessions-dates) drive_sessions_dates ;;
    admin-static-entities) drive_admin_static_entities ;;
    *) die "usage: drive health|calendar-today|sessions-dates|admin-static-entities" ;;
  esac
  echo "drive ${1}: ok" | tee -a "$EVID/drive.txt"
}

# --- evidence --------------------------------------------------------------

cmd_evidence() {
  load_state
  dc ps --format 'table {{.Service}}\t{{.Image}}\t{{.State}}\t{{.Ports}}' >"$EVID/compose-ps.txt"
  dc logs --no-color --no-log-prefix webapp 2>&1 | redact >"$EVID/webapp.log"
  dc logs --no-color --no-log-prefix postgres 2>&1 | redact >"$EVID/postgres.log"
  {
    echo "# verify-server run $RUN_ID"
    echo
    echo "- project: \`$PROJECT\` (127.0.0.1:$PORT)"
    echo "- git: \`$(git -C "$ROOT" rev-parse --short HEAD)\` on \`$(git -C "$ROOT" rev-parse --abbrev-ref HEAD)\`"
    echo "- compose: $(docker compose version --short)"
    echo "- drove: $(sed 's/^drive \(.*\): ok$/\1/' "$EVID/drive.txt" 2>/dev/null | paste -sd, - || echo none)"
    echo
    echo "## Files"
    (cd "$EVID" && ls -1)
  } >"$EVID/summary.md"

  # Guard: generated secrets must not be in anything we are about to keep.
  local token password
  token="$(sed -n 's/^IOS_BEARER_TOKEN=//p' "$RUN_DIR/env")"
  password="$(sed -n 's/^POSTGRES_PASSWORD=//p' "$RUN_DIR/env")"
  if grep -rlF -e "$token" -e "$password" "$EVID" >/dev/null; then
    grep -rlF -e "$token" -e "$password" "$EVID" >&2
    die "evidence contains a generated secret — refusing to keep it"
  fi
  echo "evidence: $EVID (secret scan clean)"
}

# --- cleanup ---------------------------------------------------------------

cmd_cleanup() {
  load_state
  echo "==> tearing down project $PROJECT (volumes + locally built image)"
  dc down -v --remove-orphans --rmi local
  rm -rf "$RUN_DIR"
  rm -f "$CURRENT"

  local left
  left="$(docker ps -a --filter "label=com.docker.compose.project=$PROJECT" -q | wc -l)"
  [ "$left" = 0 ] || die "$left container(s) of $PROJECT remain"
  left="$(docker volume ls --filter "label=com.docker.compose.project=$PROJECT" -q | wc -l)"
  [ "$left" = 0 ] || die "$left volume(s) of $PROJECT remain"
  [ -d "$EVID" ] || die "evidence directory vanished: $EVID"
  echo "cleanup: $PROJECT gone; evidence kept at $EVID ($(find "$EVID" -type f | wc -l) files)"
}

case "${1:-}" in
  launch) cmd_launch ;;
  doctor) cmd_doctor ;;
  drive) shift; cmd_drive "${1:-}" ;;
  evidence) cmd_evidence ;;
  cleanup) cmd_cleanup ;;
  *) die "usage: verify.sh launch|doctor|drive <feature>|evidence|cleanup" ;;
esac
